import { createClientFromRequest } from "npm:@base44/sdk@0.8.40";
import { createRateLimiter } from "../../shared/turnstile.ts";

// تقييد المعدّل لكل IP لمنع الإجهاد الآلي واستنزاف أرصدة الذكاء الاصطناعي (5 رسائل / 10 د)
const limiter = createRateLimiter(10 * 60 * 1000, 5);

// مساعد جدارة العام — مرشد إرشادي فقط، مخصص للصفحات العامة (صفحة الهبوط، بوابة دخول الشركات،
// بوابة دخول الموظفين قبل الجلسة). لا يتطلب جلسة ولا يجلب بيانات. يجيب عن الأسئلة العامة حول
// المنصة: الباقات، التسعير، التجربة، طلب عرض السعر، كيفية تسجيل الدخول للشركات/الموظفين،
// الميزات، التكاملات. لا ينفذ أي عملية ولا يClaims معرفة بيانات أو وضع طلبات.

export default async function (req) {
  try {
    const base44 = createClientFromRequest(req);
    const body = await req.json().catch(() => ({}));

    // حماية تقييد المعدّل قبل استدعاء LLM — تحقق آجل من IP لمنع استنزاف الأرصدة
    const ip = limiter.clientIp(req);
    if (limiter.rateLimited(ip)) {
      return Response.json({ ok: false, error: "rate_limited" }, { status: 429 });
    }

    const message = String(body.message || "").trim().slice(0, 500);
    const history: any[] = Array.isArray(body.history) ? body.history.slice(-10) : [];
    const lang = String(body.lang || "ar").slice(0, 5);
    const LANG_NAME: Record<string, string> = { ar: "العربية الفصحى", en: "English", hi: "हिन्दी", ne: "नेपाली", bn: "বাংলা", fil: "Filipino", ur: "اردو" };
    const langName = LANG_NAME[lang] || "العربية الفصحى";
    if (!message) return Response.json({ ok: false, error: "missing" }, { status: 400 });

    // لا نتحقق من جلسة هنا — المساعد عام ومتاح قبل الدخول.

    const sys =
      "أنت «مساعد جدارة» الذكي على موقع منصة جدارة لإدارة الموارد البشرية. مهمتك الإرشاد والتوجيه العام فقط — تساعد الزائر/العميل المحتمل على فهم المنصة وأنظمتها وكيفية البدء.\n\nقواعد صارمة:\n- أنت مرشد إرشادي فقط: لا تنفذ أي عملية (لا إنشاء حساب، لا تفعيل تجربة، لا إرسال رسالة، لا اعتماد، لا فاتورة) نيابة عن المستخدم. اكتفي بتوجيهه للأزرار والصفحات والخطوات الصحيحة.\n- لا تخترع أسعاراً أو أرقاماً غير المعروضة في المنصة. إن لم تعرف سعراً محدداً وجهه لصفحة «طلب عرض سعر».\n- لا تطلب معلومات حساسة (كلمة مرور، رموز تحقق، أرقام هوية، حسابات بنكية). لا تشارك أي رابط دعوة أو رمز دخول.\n- كن مختصراً وودوداً، بالعربية الفصحى البسيطة الواضحة.\n\nخريطة المنصة التي تُرشد إليها:\n- صفحة الهبوط: تعرض الميزات، الباقات، حاسبات مجانية (نهاية الخدمة، عقود، qiwa/mudad، wps)، نظام تجربة مجانية 30 يوماً، طلب عرض سعر، نموذج تواصل.\n- للحصول على تجربة: زر «ابدأ تجربتك المجانية» في صفحة الهبوط — يفتح نموذجاً (اسم المنشأة، البريد، الهاتف، عدد الموظفين) ثم يُفعّل المالك التجربة.\n- لطلب عرض سعر مخصص: صفحة «طلب عرض سعر» (رابط /quote) تملأ بيانات المنشأة وعدد الموظفين والباقة المرغوبة.\n- الدخول للمالك/المسؤول: بوابة الشركات (/company-login) — تسجيل دخول بشركة مسجلة في جدارة ببريد ورقم موحّد موثّق من المالك.\n- الدخول للموظف: بوابة الموظف الذاتية (/portal) — بالهوية الوطنية وتاريخ الميلاد.\n- استثناءات/دعم: صفحة «تواصل معنا» (/contact) لإرسال رسالة لفريق جدارة، أو الرقم المجاني.\n- ميزات المنصة: إدارة موظفين، حضور وبصمة جغرافية، رواتب وبنوك (WPS)، تأمينات اجتماعية (GOSI)، نهاية الخدمة، إجازات وسلف وانتدابات بمسار اعتماد (مدير ← موارد بشرية ← مالية)، أداء وتدريب وتطوير، توظيف واختبار فترة، تقارير وتحليلات، تراخيص حكومية، بوابة موظف ذاتية متعددة اللغات.\n-أهداف جدارة: تبسيط الموارد البشرية للمنشآت السعودية وفق الأنظمة (نظام العمل، التأمينات، التوطين).\n\nأجب دائماً بإرشاد واضح ومختصر؛ إن كان السؤال خارج نطاق جدارة اعتذر بلطف ووجّه لقناة التواصل الرسمية.\n\nمهم جداً: أجب دائماً بلغة " + langName + " فقط، مهما كانت لغة رسالة المستخدم — أي رد يجب أن يكون بهذه اللغة.";

    const msgs = [
      { role: "system", content: sys },
      ...history.map((h) => ({ role: h.role === "user" ? "user" : "assistant", content: String(h.content) })),
      { role: "user", content: message },
    ];

    const res = await base44.integrations.Core.InvokeLLM({
      prompt: msgs.map((m) => m.role + ":\n" + m.content).join("\n\n"),
      model: "automatic",
    });
    const reply = (typeof res === "string" ? res : res?.response || res?.reply || res?.text || res?.content || "")
      .toString().trim() || "عذراً، لم أتمكن من صياغة الرد الآن. حاول مرة أخرى.";

    return Response.json({ ok: true, reply });
  } catch (e) {
    return Response.json({ ok: false, error: String((e as any)?.message || e) }, { status: 500 });
  }
}